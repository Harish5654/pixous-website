/* ============================================================
   Apply translations across the page
   ============================================================ */
function setLanguage(code) {
  if (!TRANSLATIONS[code]) code = 'en';
  const dict = TRANSLATIONS[code];
  document.documentElement.lang = code;
  localStorage.setItem('pixous_lang', code);

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key] !== undefined) el.placeholder = dict[key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (dict[key] !== undefined) el.innerHTML = dict[key];
  });

  // Update active flag in language dropdown
  document.querySelectorAll('.lang-dropdown button').forEach(b => b.classList.toggle('active', b.dataset.lang === code));
  const langBtn = document.querySelector('.lang-btn .lang-current');
  const lang = LANGUAGES.find(l => l.code === code);
  if (langBtn && lang) langBtn.textContent = lang.code.toUpperCase();
}

function getCurrentLang() {
  return localStorage.getItem('pixous_lang') || 'en';
}

function buildLanguageSwitcher() {
  const switchers = document.querySelectorAll('.lang-dropdown');
  switchers.forEach(dd => {
    dd.innerHTML = LANGUAGES.map(l =>
      `<button data-lang="${l.code}"><span class="lang-flag">${l.flag}</span><span>${l.name}</span></button>`
    ).join('');
    dd.querySelectorAll('button').forEach(b => {
      b.addEventListener('click', () => {
        setLanguage(b.dataset.lang);
        b.closest('.lang-switch').classList.remove('open');
      });
    });
  });
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', e => {
      e.stopPropagation();
      btn.closest('.lang-switch').classList.toggle('open');
    });
  });
  document.addEventListener('click', () => {
    document.querySelectorAll('.lang-switch.open').forEach(s => s.classList.remove('open'));
  });
}
